#!/usr/bin/env bun
/**
 * Build the Phase WASM bridge without wasm-bindgen.
 *
 * The upstream engine uses nightly-only `if let` guards. We inject the feature
 * gates through RUSTFLAGS instead of rewriting rules code. A nightly toolchain
 * with rust-src is required when prebuilt wasm32 std is unavailable;
 * `-Z build-std` compiles it from source.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const cargo = process.env.CARGO ?? 'cargo';
const profile = process.env.ENGINE_PROFILE ?? 'release';
const target = 'wasm32-unknown-unknown';
const targetDir = process.env.CARGO_TARGET_DIR ?? 'target';

const featureFlags = [
  '-Zcrate-attr=feature(if_let_guard)',
  '-Zcrate-attr=feature(let_chains)',
  '-Zthreads=1',
  '-Zshare-generics',
  '-Zmir-opt-level=0'
];
const wasmFlags = [
  '-C', 'link-arg=-z',
  '-C', 'link-arg=stack-size=16777216',
  '--cfg', 'getrandom_backend="custom"'
];

const args = [
  cargo, 'build',
  '--target', target,
  '-p', 'mtg-engine-wasm',
  '--lib',
  '--profile', profile,
  '-j', '1'
];
if (process.env.ENGINE_BUILD_STD === '1') args.push('-Z', 'build-std=core,alloc,std,panic_abort');
if (process.env.CARGO_OFFLINE === '1') {
  // The offline bootstrap must not depend on a path left over from another
  // session: the config is (re)written from this checkout's `vendor/`.
  const vendorDir = resolve(process.env.MESA_VENDOR_DIR ?? 'vendor');
  if (!existsSync(vendorDir)) {
    console.error(`No hay crates vendorizadas en ${vendorDir}. Ejecuta: bun scripts/vendor-crates.ts`);
    process.exit(1);
  }
  mkdirSync('.cargo', { recursive: true });
  writeFileSync(
    '.cargo/offline.toml',
    [
      '# Generated by scripts/build-engine.ts — do not commit.',
      '[source.crates-io]',
      'replace-with = "mesa-vendor"',
      '',
      '[source.mesa-vendor]',
      `directory = ${JSON.stringify(vendorDir)}`,
      '',
      '[net]',
      'offline = true',
      ''
    ].join('\n')
  );
  args.push('--offline', '--config', '.cargo/offline.toml');
}
if (process.env.CARGO_LOCKED === '1') args.push('--locked');

const env = {
  ...process.env,
  CARGO_BUILD_JOBS: '1',
  CARGO_INCREMENTAL: '0',
  // `MESA_RUSTFLAGS_EXTRA` goes last, so a machine with little RAM can lower
  // the peak without editing this script (see docs/BROWSER-RUNBOOK.md §3.1).
  RUSTFLAGS: [process.env.RUSTFLAGS, ...featureFlags, ...wasmFlags, process.env.MESA_RUSTFLAGS_EXTRA]
    .filter(Boolean)
    .join(' '),
  // glibc gives each thread its own arena; the engine crate does not need one
  // per thread to compile, and on a 4 GB box the difference is a killed build.
  MALLOC_ARENA_MAX: process.env.MALLOC_ARENA_MAX ?? '1'
};

/**
 * Say how much RAM this needs *before* spending the build, not after.
 *
 * Measured on a 3.9 GB box: rustc reaches ~3.6 GB of RSS while type-checking
 * `crates/phase-engine` (1.39 M lines, one crate) and is then killed by the OOM
 * killer. Lowering opt-level, codegen-units, mirror optimizations, the LLVM
 * backend or `--emit=metadata` does not move that peak: it is the front end.
 * Five configurations were tried; the numbers are in docs/ENGINE-ARTIFACT.md.
 * Without this warning the next person loses the same 20 minutes we did.
 */
function memoryWarning(): void {
  const meminfo = existsSync('/proc/meminfo') ? readFileSync('/proc/meminfo', 'utf8') : '';
  const totalKb = Number(/^MemTotal:\s+(\d+)/m.exec(meminfo)?.[1] ?? 0);
  const swapKb = Number(/^SwapTotal:\s+(\d+)/m.exec(meminfo)?.[1] ?? 0);
  if (!totalKb) return; // not Linux, or not readable: say nothing rather than guess
  const totalGb = (totalKb + swapKb) / 1024 / 1024;
  if (totalGb >= 7) return;
  console.warn(
    `\n⚠ Esta máquina tiene ${totalGb.toFixed(1)} GiB de memoria (${(totalKb / 1024 / 1024).toFixed(1)} GiB de RAM + ` +
      `${(swapKb / 1024 / 1024).toFixed(1)} GiB de swap).\n` +
      '  Compilar `phase-engine` pidió ~3.6 GB de RSS y murió por OOM en todas las\n' +
      '  configuraciones probadas. Si esta termina, es la excepción; si muere con\n' +
      '  `signal: 9`, no es un flag que falte: es RAM.\n' +
      '  Camino documentado: docs/ENGINE-ARTIFACT.md (§2 el muro, §3 otra máquina,\n' +
      '  §5 traer el binario con `bun run engine:fetch`).\n' +
      '  Para seguir igual: MESA_ALLOW_LOW_MEMORY=1.\n'
  );
  if (process.env.MESA_ALLOW_LOW_MEMORY !== '1') process.exit(3);
}

memoryWarning();
console.log(`Building mtg-engine-wasm (${profile}, ${target})…`);
const result = Bun.spawnSync(args, { stdout: 'inherit', stderr: 'inherit', env });
if (result.exitCode !== 0) process.exit(result.exitCode ?? 1);

const src = `${targetDir}/${target}/${profile}/mtg_engine_wasm.wasm`;
const out = 'static/wasm/mtg_engine_wasm.wasm';
await Bun.write(out, Bun.file(src));
const bytes = Bun.file(out).size;
console.log(`Wrote ${out} (${(bytes / 1024 / 1024).toFixed(2)} MiB)`);
if (process.env.ENGINE_OPTIMIZE === '1') {
  const opt = Bun.spawnSync(['bun', 'scripts/optimize-wasm.ts'], { stdout: 'inherit', stderr: 'inherit', env: process.env });
  if (opt.exitCode !== 0) process.exit(opt.exitCode ?? 1);
}
