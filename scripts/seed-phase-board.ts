  card({
    name,
    zone: "Battlefield",
    power,
    toughness,
    base_power: power,
    base_toughness: toughness,
    card_types: { supertypes: [], core_types: ["Creature"], subtypes: [] },
    mana_cost: { type: "Cost", shards: ["Green"], generic: power },
    color: ["Green"],
    ...extra,
  });

const inHand = (name: string, shards: string[], generic: number) =>
  card({
    name,
    zone: "Hand",
    entered_battlefield_turn: null,
    mana_cost: { type: "Cost", shards, generic },
    card_types: { supertypes: [], core_types: ["Creature"], subtypes: [] },
    power: 2,
    toughness: 2,
    base_power: 2,
    base_toughness: 2,
    color: ["White"],
  });

